# ---------- 其他科：依「主體」自動分章 ----------
def auto(sub, order, rename=None, manual=None):
    rename = rename or {}; manual = manual or {}
    chapters = {t: [] for t in order}
    for c in sorted(idx[sub], key=lambda c: -idx[sub][c]['n']):
        body = c[3:]
        key = manual.get(c) or rename.get(body.split(' ')[0], body.split(' ')[0])
        if key not in chapters:
            chapters.setdefault('未歸類', []).append(c)
        else:
            chapters[key].append(c)
    return chapters

